#!/usr/bin/env python3
"""Generate src/airports_data.h from the OurAirports airports.csv.

Keeps, for the chosen country (default US):
  * large airports (always) and medium airports that have an IATA code: drawn on the
    scope as markers, large ones with a label (kind 1 and 0);
  * every other open airport (small fields, medium ones without IATA): never drawn on
    their own, but kept so a user can pin one by code on the config page (kind 2).
Heliports, seaplane bases, balloonports and closed airports are dropped.

Emits int16 lat/lon (degrees * 100), the 3-letter IATA code (may be empty), the 4-character
ICAO/GPS identifier, and the kind.

Usage:
    python3 tools/gen_airports.py /path/to/airports.csv src/airports_data.h [--country US]

Source data: OurAirports (public domain). https://ourairports.com/data/
"""
import argparse
import csv

SCALE = 100.0
KIND_MEDIUM, KIND_LARGE, KIND_PIN_ONLY = 0, 1, 2


def ident_of(r):
    """The ICAO/GPS-style identifier, up to 4 characters; '' when the row has none."""
    for key in ("icao_code", "gps_code", "ident", "local_code"):
        v = (r.get(key) or "").strip().upper()
        if 3 <= len(v) <= 4 and v.isalnum():
            return v
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?", default="/tmp/airports.csv")
    ap.add_argument("dst", nargs="?", default="src/airports_data.h")
    ap.add_argument("--country", default="US", help="ISO 3166-1 country code to keep")
    args = ap.parse_args()

    rows = []
    with open(args.src, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["iso_country"] != args.country:
                continue
            t = r["type"]
            iata = (r.get("iata_code") or "").strip().upper()[:3]
            if t == "large_airport":
                kind = KIND_LARGE
            elif t == "medium_airport" and iata:
                kind = KIND_MEDIUM
            elif t in ("medium_airport", "small_airport"):
                kind = KIND_PIN_ONLY
            else:
                continue
            icao = ident_of(r)
            if kind == KIND_PIN_ONLY and not icao:
                continue                    # nothing a user could type to pin it
            try:
                lat = float(r["latitude_deg"])
                lon = float(r["longitude_deg"])
            except (ValueError, KeyError):
                continue
            lat_s = max(-9000, min(9000, round(lat * SCALE)))
            lon_s = max(-18000, min(18000, round(lon * SCALE)))
            rows.append((lat_s, lon_s, iata, icao, kind))

    n_large = sum(1 for r in rows if r[4] == KIND_LARGE)
    n_med = sum(1 for r in rows if r[4] == KIND_MEDIUM)
    n_pin = sum(1 for r in rows if r[4] == KIND_PIN_ONLY)
    with open(args.dst, "w") as f:
        f.write("// Auto-generated by tools/gen_airports.py — DO NOT EDIT.\n")
        f.write("// Source: OurAirports (public domain). Country: %s.\n" % args.country)
        f.write("// %d airports (%d large w/ label, %d medium, %d pin-only). lat,lon are int16 deg*%d.\n"
                % (len(rows), n_large, n_med, n_pin, int(SCALE)))
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define AIRPORT_SCALE %d\n" % int(SCALE))
        f.write("#define AIRPORT_NUM %d\n\n" % len(rows))

        f.write("static const int16_t AIRPORT_LAT[AIRPORT_NUM] = {\n")
        for i in range(0, len(rows), 18):
            f.write("  " + ",".join(str(r[0]) for r in rows[i:i + 18]) + ",\n")
        f.write("};\n\n")

        f.write("static const int16_t AIRPORT_LON[AIRPORT_NUM] = {\n")
        for i in range(0, len(rows), 18):
            f.write("  " + ",".join(str(r[1]) for r in rows[i:i + 18]) + ",\n")
        f.write("};\n\n")

        f.write("// 1 = large airport (gets an IATA label), 0 = medium (marker only),\n")
        f.write("// 2 = pin-only (drawn only when the user pins it by code).\n")
        f.write("static const uint8_t AIRPORT_KIND[AIRPORT_NUM] = {\n")
        for i in range(0, len(rows), 32):
            f.write("  " + ",".join(str(r[4]) for r in rows[i:i + 32]) + ",\n")
        f.write("};\n\n")

        f.write("// 3-letter IATA code (may be empty).\n")
        f.write("static const char AIRPORT_IATA[AIRPORT_NUM][4] = {\n")
        for i in range(0, len(rows), 12):
            f.write("  " + ",".join('"%s"' % r[2] for r in rows[i:i + 12]) + ",\n")
        f.write("};\n\n")

        f.write("// ICAO / GPS identifier, 3-4 characters (may be empty for a large airport without one).\n")
        f.write("static const char AIRPORT_ICAO[AIRPORT_NUM][5] = {\n")
        for i in range(0, len(rows), 10):
            f.write("  " + ",".join('"%s"' % r[3] for r in rows[i:i + 10]) + ",\n")
        f.write("};\n")

    bytes_total = len(rows) * (2 + 2 + 1 + 4 + 5)
    print("airports: %d (%d large, %d medium, %d pin-only)" % (len(rows), n_large, n_med, n_pin))
    print("flash:    ~%.1f KB" % (bytes_total / 1024.0))
    print("written:  %s" % args.dst)


if __name__ == "__main__":
    main()
